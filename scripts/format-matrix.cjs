// Writes docs/FORMATS.md from the conversion registry (electron/domain/capabilities.cjs), so the
// documented matrix is the one the code offers. test/electron/docs.test.cjs fails when it is stale.
//   node scripts/format-matrix.cjs          rewrite docs/FORMATS.md
const fs = require('fs');
const path = require('path');
const { KINDS, BY_EXT } = require('../electron/domain/formats.cjs');
const { capabilityFor } = require('../electron/domain/capabilities.cjs');

const ENGINE = { ffmpeg: 'ffmpeg', image: 'sharp (worker)', pdf: 'Poppler', office: 'LibreOffice', ebook: 'Calibre', archive: '7-Zip' };
const FIDELITY = {
  lossless: 'content preserved',
  lossy: 're-encoded (quality setting)',
  flatten: 'transparency filled white',
  'single-frame': 'first frame only',
  rasterize: 'pages/vector become pixels',
  'vector-approx': 'traced, limited colours',
  reconstruct: 'layout rebuilt, may change',
  'text-only': 'text only, no formatting',
  'first-sheet': 'first sheet, values only',
  repack: 'contents kept, container changes',
  'audio-only': 'video track dropped',
  resized: 'max 256x256',
  resampled: 'fewer frames/s, max 720 px wide',
};
// Directions exercised by test/electron/engines.test.cjs and documents.test.cjs on a host with the
// engine installed.
const ENGINE_TESTED = new Set([
  'image:jpg', 'image:webp', 'image:avif', 'image:tiff', 'image:gif', 'image:pdf', 'image:svg', 'image:bmp', 'image:ico', 'image:png',
  'audio:mp3', 'audio:m4a', 'audio:ogg', 'audio:flac', 'audio:opus', 'audio:aac',
  'video:mp4', 'video:mov', 'video:webm', 'video:avi', 'video:mp3', 'video:wav', 'video:gif', 'video:apng',
  'gif:mp4', 'gif:webm', 'gif:apng', 'gif:png',
  'pdf:png', 'pdf:jpg', 'pdf:txt', 'pdf:docx',
  'doc:docx', 'doc:pdf', 'sheet:xlsx', 'sheet:ods',
  'archive:7z', 'archive:tar', 'archive:tar.gz', 'archive:zip',
  'video:mkv', 'video:m4a', 'video:ogg', 'video:flac', 'audio:wav',
  'apng:gif', 'apng:mp4', 'apng:webm', 'apng:png',
  'svg:png', 'svg:jpg', 'svg:webp', 'svg:pdf',
  // test/electron/documents.test.cjs: content and formatting checked inside the output
  'doc:odt', 'doc:rtf', 'doc:txt', 'doc:epub',
  'sheet:pdf', 'sheet:csv', 'slides:pdf', 'slides:pptx', 'slides:odp',
]);

function render() {
  const lines = [
    '# Supported conversions',
    '',
    'Generated by `node scripts/format-matrix.cjs` from `electron/domain/capabilities.cjs`; do not edit by hand.',
    'A direction is offered only when its engine is installed and passed its probe (ToolRegistry).',
    '"Tested" = covered by `test/electron/engines.test.cjs` or `documents.test.cjs` on a host with that engine; Windows-bundled',
    'engines still need the Windows run in docs/TESTING.md.',
    '',
  ];
  for (const [kind, { label, targets }] of Object.entries(KINDS)) {
    lines.push(`## ${kind} (${label})`, '', `Recognised extensions: ${BY_EXT[kind]?.join(', ') || '(content only)'}`, '', '| Target | Engine | What changes | Tested |', '| --- | --- | --- | --- |');
    for (const t of targets) {
      const cap = capabilityFor(kind, '', t);
      lines.push(`| ${t} | ${ENGINE[cap.adapter]} | ${FIDELITY[cap.fidelity]} | ${ENGINE_TESTED.has(`${kind}:${t}`) ? 'yes' : 'not yet'} |`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

if (require.main === module) {
  fs.writeFileSync(path.join(__dirname, '..', 'docs', 'FORMATS.md'), render());
  console.log('docs/FORMATS.md written');
}

module.exports = { render };
